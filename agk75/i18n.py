class Msg(Exception):
    """번역할 수 있는 오류. str() 은 영어다."""

    def __init__(self, key, **params):
        super().__init__(key)
        self.key, self.params = key, params

    def __str__(self):
        return render("en", self.key, self.params)


class MsgError(Msg, ValueError):
    """입력 검사 실패(Msg 를 올린다)."""


def lang():
    return getattr(_local, "lang", None) or _current


def set_lang(code):
    global _current
    _current = norm(code)


@contextlib.contextmanager
def use(lang_code):
    prev = getattr(_local, "lang", None)
    _local.lang = norm(lang_code)
    try:
        yield
    finally:
        _local.lang = prev


def t(key, **params):
    return render(lang(), key, params)


def msg(exc):
    """예외 -> 현재 언어 문구(Msg 가 아니면 str)."""
    return render(lang(), exc.key, exc.params) if isinstance(exc, Msg) else str(exc)


def system_lang():
    """콘솔 출력용: Windows 사용자 UI 언어(ko/zh, 그 밖은 en)."""
    try:
        import ctypes
        primary = ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0x3FF
    except (AttributeError, OSError):
        return "en"
    return {0x12: "ko", 0x04: "zh"}.get(primary, "en")
