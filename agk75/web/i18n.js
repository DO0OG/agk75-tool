const I18N = {
  langs: [["ko", "한국어"], ["en", "English"], ["zh", "中文"]],
  lang: "ko",
  // 저장된 값 -> 브라우저 언어(ko→ko, zh→zh, 그 외 en)
  detect() {
    let saved = null;
    try { saved = localStorage.getItem("agk75.lang"); } catch (e) { /* 저장소를 못 쓰면 브라우저 언어를 쓴다 */ }
    if (I18N_DICT[saved]) return saved;
    const nav = (typeof navigator !== "undefined" && navigator.language || "en").toLowerCase();
    return nav.startsWith("ko") ? "ko" : nav.startsWith("zh") ? "zh" : "en";
  },
  set(lang) {
    I18N.lang = I18N_DICT[lang] ? lang : "en";
    try { localStorage.setItem("agk75.lang", I18N.lang); } catch (e) { /* 저장 실패는 무시한다 */ }
    I18N.apply();
  },
  // 정적 문구([data-i18n])와 문서 제목·언어 속성을 다시 채운다
  apply() {
    if (typeof document === "undefined") return;
    document.documentElement.lang = I18N.lang === "zh" ? "zh-CN" : I18N.lang;
    document.title = t("app.title");
    document.querySelectorAll("[data-i18n]").forEach((e) => { e.textContent = t(e.dataset.i18n); });
  },
  has: (key) => key in I18N_DICT[I18N.lang],
};

// t("toast.profile", { n: 2 }) -> "프로필 2 적용됨". 없는 키는 ko 사전, 그래도 없으면 키 그대로.
function t(key, params) {
  const s = (I18N_DICT[I18N.lang] || {})[key] ?? I18N_DICT.ko[key] ?? key;
  return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m)) : s;
}

if (typeof module !== "undefined" && module.exports) module.exports = { I18N_DICT, I18N, t };
